package ru.aasmc.tracing.collector.domain;

/** Kinds of broken business rules. The REST layer maps them to stable error codes for clients. */
public enum ViolationCode {
    // trace data
    INVALID_TRACE_ID,
    INVALID_SPAN_ID,
    INVALID_TIME_RANGE,
    INVALID_SPAN,
    INVALID_TRACE_SUMMARY,
    INVALID_ATTRIBUTE_KEY,
    INVALID_ATTRIBUTE_TYPE,
    TOO_MANY_ATTRIBUTES,

    // enrichment sources
    INVALID_NAME,
    INVALID_TOPIC,
    INVALID_JSON_POINTER,
    INVALID_TRACE_CONTEXT,
    INVALID_SCOPE,
    INVALID_MAPPING,
    INVALID_TARGET_KEY,
    DUPLICATE_TARGET_KEY,
    RESERVED_KEY,
    INVALID_TRANSFORM,
    INVALID_SOURCE_TRANSITION,

    // indexed attributes and sensitive data
    INVALID_INDEX_TRANSITION,
    BUILT_IN_KEY,
    RETAINED_KEY_MUST_BE_INDEXED,
    INVALID_DIGEST_TRANSFORM,
    PERSONAL_DATA_RETAINED_IN_CLEAR,
    SECRET_RETAINED_IN_CLEAR,

    // retention
    FULL_DATA_DAYS_TOO_SMALL,
    FULL_DATA_DAYS_BELOW_MERGE_WINDOW,
    INVALID_DIGEST_DAYS,

    // correlation
    INVALID_OPERATION_DEFINITION,
    INVALID_MERGE_WINDOW,
    UNKNOWN_STEP_LABEL,
    INVALID_OUTCOME_RULE,
    INVALID_CORRELATION_VALUE,
    INVALID_BUSINESS_OPERATION,

    // digests
    INVALID_DIGEST_TRANSITION
}
